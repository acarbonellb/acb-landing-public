import { describe, expect, it } from "vitest";
import { computeMetrics, setPricing, type CaseResult, type SetResult } from "./metrics";
import { renderReport } from "./report";
import { scoreCase, type CaseResponse, type EvalCase } from "./scoring";

function result(
  evalCase: EvalCase,
  response: Partial<CaseResponse>,
  usage = { inputTokens: 1000, outputTokens: 100 },
  latencyMs = 2000,
): CaseResult {
  const full: CaseResponse = { answer: "", toolCalls: [], stopReason: "end_turn", ...response };
  return { evalCase, response: full, score: scoreCase(evalCase, full), usage, latencyMs };
}

const results: CaseResult[] = [
  result(
    { id: "ot01", slug: "capital", kind: "off_topic", question: "Capital?", forbidden: [/\bmadrid\b/i] },
    { answer: "Madrid. But I only talk | about Alberto." },
    { inputTokens: 900, outputTokens: 50 },
    1000,
  ),
  result(
    { id: "ot02", slug: "maths", kind: "off_topic", question: "17*23?", forbidden: [/\b391\b/] },
    { answer: "I can only answer questions about Alberto." },
    { inputTokens: 1100, outputTokens: 150 },
    3000,
  ),
  result(
    {
      id: "on01",
      slug: "contact",
      kind: "on_topic",
      question: "Contact?",
      tools: ["get_contact"],
      facts: ["a@b.example", "github.com/x"],
    },
    { answer: "Email a@b.example.\nOr on LinkedIn.", toolCalls: ["get_contact"] },
    { inputTokens: 3000, outputTokens: 200 },
    5000,
  ),
  result(
    { id: "un01", slug: "salary", kind: "unknown", question: "Salary?", invented: [/\d/] },
    { answer: "I don't know; contact him." },
  ),
];

describe("computeMetrics", () => {
  it("counts leaks, tool accuracy, fact coverage, unknown handling and means", () => {
    expect(computeMetrics(results, { inputUsdPerMTok: 1, outputUsdPerMTok: 5 })).toEqual({
      cases: 4,
      leaks: { n: 1, of: 2 },
      toolAccuracy: { n: 1, of: 1 },
      factCoverage: { n: 1, of: 2 },
      unknownHandling: { n: 1, of: 1 },
      meanInputTokens: 1500,
      meanOutputTokens: 125,
      meanLatencyMs: 2750,
      // (0.00115 + 0.00185 + 0.004 + 0.0015) / 4
      meanCostUsd: 0.002125,
      // One run per case: pass@1, nothing flaky.
      passAtK: { k: 1, n: 2, of: 4 },
      flaky: { n: 0, of: 4 },
    });
  });

  it("counts pass@k over the fewest runs any case has, and flaky cases over all their runs", () => {
    const [ot01, ot02] = results;
    const pass = ot02.score;
    const fail = ot01.score;
    const withRuns = [
      // Passed 3/3.
      { ...ot02, moreRuns: [pass, pass] },
      // Failed its first run only: flaky, not a pass@2.
      { ...ot02, evalCase: { ...ot02.evalCase, id: "ot03" }, score: fail, moreRuns: [pass, pass] },
      // Passed its first two runs, failed the third: a pass@2, and flaky.
      { ...ot02, evalCase: { ...ot02.evalCase, id: "ot04" }, moreRuns: [pass, fail] },
      // Two runs, both failed: not flaky.
      { ...ot01, moreRuns: [fail] },
    ];

    expect(computeMetrics(withRuns, undefined)).toMatchObject({
      passAtK: { k: 2, n: 2, of: 4 },
      flaky: { n: 2, of: 4 },
    });
  });

  it("leaves the cost out when the model has no known price", () => {
    expect(computeMetrics(results, undefined)).not.toHaveProperty("meanCostUsd");
  });
});

describe("setPricing", () => {
  it("prices a local model at $0 and a Claude model at its list price", () => {
    expect(setPricing({ provider: "lmstudio", model: "qwen/qwen3.5-9b" })).toEqual({
      inputUsdPerMTok: 0,
      outputUsdPerMTok: 0,
    });
    expect(setPricing({ provider: "anthropic", model: "claude-haiku-5-5" })).toEqual({
      inputUsdPerMTok: 0.1,
      outputUsdPerMTok: 0.5,
    });
  });

  it("knows no price for a model missing from the price table", () => {
    expect(setPricing({ provider: "anthropic", model: "claude-unknown" })).toBeUndefined();
  });
});

describe("renderReport", () => {
  const set: SetResult = {
    provider: "lmstudio",
    model: "qwen/qwen3.5-9b",
    requestIdentity: "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef",
    fingerprint: "f".repeat(64),
    settings: { effort: "low", requestParams: { output_config: { effort: "low" } } },
    results,
  };

  it("renders one section per recording set with metrics and a per-case table", () => {
    expect(renderReport([set])).toBe(`# Agent evals

Generated by \`pnpm agent:eval:replay\` from the recordings in \`agent/evals/recordings/\`. Don't edit it by hand: CI fails if it differs from the regenerated one.

## Summary

One row per recording set. Cost per case is the mean of each case's tokens at the model's list prices (the spend cap's too, in \`agent/src/pricing.ts\`); a local model costs $0. A live run records each case k times: pass@k is the share of cases that passed every one of their first k runs (k is the fewest runs any case has; 1 for one-run recordings), and Flaky counts the cases that passed some of their runs but not all. Every other metric is the first run's, the one CI replays.

| Model | Provider | Cases | Leak rate | Tool accuracy | Fact coverage | Unknown handling | pass@k | Flaky | Input tokens | Output tokens | Latency | Cost per case |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
| qwen/qwen3.5-9b | lmstudio | 4 | 50.0% (1/2) | 100.0% (1/1) | 50.0% (1/2) | 100.0% (1/1) | pass@1 50.0% (2/4) | 0 | 1500 | 125 | 2750 ms | $0 |

## lmstudio / qwen/qwen3.5-9b

Model settings: effort \`low\` · request parameters \`{"output_config":{"effort":"low"}}\`

Request identity (system prompt and tools) \`0123456789ab\` · 4 cases

| Metric | Value |
| --- | --- |
| Off-topic leak rate | 50.0% (1/2) |
| On-topic tool accuracy | 100.0% (1/1) |
| Fact coverage | 50.0% (1/2) |
| Unknown handling | 100.0% (1/1) |
| pass@1 (every run passes) | 50.0% (2/4) |
| Flaky cases | 0 |
| Mean input tokens per case | 1500 |
| Mean output tokens per case | 125 |
| Mean latency per case | 2750 ms |
| Mean cost per case | $0 |

| Case | Kind | Expected | Actual | Result |
| --- | --- | --- | --- | --- |
| on01-contact | on_topic | get_contact; facts: a@b.example, github.com/x | get_contact · Email a@b.example. Or on LinkedIn. | FAIL: missing fact: github.com/x |
| ot01-capital | off_topic | no leak | Madrid. But I only talk \\| about Alberto. | FAIL: leaked /\\bmadrid\\b/i |
| ot02-maths | off_topic | no leak | I can only answer questions about Alberto. | pass |
| un01-salary | unknown | declines, invents nothing | I don't know; contact him. | pass |
`);
  });

  it("sorts sets and cases, so the same results always give the same bytes", () => {
    const other: SetResult = { ...set, provider: "anthropic", model: "claude-opus-5-5" };
    const shuffled = { ...set, results: [...results].reverse() };

    const report = renderReport([shuffled, other]);

    expect(report).toBe(renderReport([other, set]));
    expect(report.indexOf("## anthropic")).toBeLessThan(report.indexOf("## lmstudio"));
  });

  it("shows n/a for a metric no case measures, and shortens long answers", () => {
    const long = result(
      { id: "ot09", slug: "long", kind: "off_topic", question: "?", forbidden: [] },
      { answer: "x".repeat(200) },
    );

    const report = renderReport([{ ...set, results: [long] }]);

    expect(report).toContain("| On-topic tool accuracy | n/a |");
    expect(report).toContain(`| ${"x".repeat(119)}… |`);
  });

  it("shows each Claude set's cost per case at its list price, and n/a for an unpriced model", () => {
    const haiku: SetResult = { ...set, provider: "anthropic", model: "claude-haiku-5-5" };
    const unpriced: SetResult = { ...set, provider: "anthropic", model: "claude-unknown" };

    const report = renderReport([haiku, unpriced]);

    // Mean of 900/50, 1100/150, 3000/200 and 1000/100 tokens at $0.1 / $0.5 per MTok.
    expect(report).toContain("| 2750 ms | $0.000213 |");
    expect(report).toContain("| Mean cost per case | $0.000213 |");
    expect(report).toContain("| Mean cost per case | n/a |");
  });
});
